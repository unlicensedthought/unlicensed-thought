// Compiles the phosphene theme from the vendored piggy token subset into CSS variables.
// `--check` compares it with the upstream token set named by PIGGY_TOKENS_UPSTREAM.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const VENDORED = resolve(root, 'tokens/phosphene.tokens.json');
const UPSTREAM = process.env.PIGGY_TOKENS_UPSTREAM ?? '';
const OUT = resolve(root, 'src/lib/styles/tokens.css');
const THEME = 'phosphene';
const AXES = ['font', 'measure', 'radius'];

/** @param {any} tokens */
export function pick(tokens) {
  return {
    primitive: tokens.primitive[THEME],
    semantic: tokens.semantic[THEME],
    ...Object.fromEntries(AXES.map((a) => [a, tokens[a]]))
  };
}

/** @param {any} tokens @param {any} value @returns {any} */
function resolveRef(tokens, value) {
  const m = typeof value === 'string' && value.match(/^\{([^}]+)\}$/);
  if (!m) return value;
  let node = tokens;
  for (const part of m[1].split('.')) {
    node = node?.[part];
    if (node === undefined) throw new Error(`unresolved token reference ${value}`);
  }
  return resolveRef(tokens, node.$value ?? node);
}

/** @param {any} v */
const fam = (v) => (Array.isArray(v) ? v.map((f) => (/\s/.test(f) && !f.includes('-') ? `'${f}'` : f.includes(' ') ? `'${f}'` : f)).join(', ') : v);

/** @param {any} tokens @returns {string} */
export function compile(tokens) {
  const { semantic } = pick(tokens);
  if (!semantic) throw new Error(`no semantic.${THEME} in token set`);
  const lines = [];
  for (const [role, v] of Object.entries(semantic)) {
    if (role.startsWith('$')) continue;
    lines.push(`  --ut-${role}: ${resolveRef(tokens, v)};`);
  }
  for (const k of ['display', 'body']) lines.push(`  --ut-font-${k}: ${fam(resolveRef(tokens, tokens.font[k].$value))};`);
  lines.push(`  --ut-font-mono: 'JetBrains Mono', ui-monospace, monospace;`);
  for (const [k, v] of Object.entries(tokens.measure)) if (!k.startsWith('$')) lines.push(`  --ut-${k}: ${String(v.$value).replaceAll('--piggy-', '--ut-')};`);
  for (const [k, v] of Object.entries(tokens.radius)) if (!k.startsWith('$')) lines.push(`  --ut-radius-${k}: ${v.$value};`);
  return `/* GENERATED by scripts/tokens.mjs from tokens/phosphene.tokens.json (piggy:${THEME}). Do not edit. */\n:root {\n  color-scheme: dark;\n${lines.join('\n')}\n}\n`;
}

function main() {
  const vendored = JSON.parse(readFileSync(VENDORED, 'utf8'));
  if (process.argv.includes('--check')) {
    if (!UPSTREAM || !existsSync(UPSTREAM)) {
      console.error(`tokens --check: FAIL set PIGGY_TOKENS_UPSTREAM to the upstream piggy token file (got '${UPSTREAM}')`);
      process.exit(2);
    }
    const a = JSON.stringify(pick(vendored));
    const b = JSON.stringify(pick(JSON.parse(readFileSync(UPSTREAM, 'utf8'))));
    if (a !== b) {
      console.error('tokens --check: FAIL vendored phosphene differs from upstream; re-vendor it');
      process.exit(1);
    }
    console.log('tokens --check: OK vendored phosphene matches upstream');
    return;
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, compile(vendored));
  console.log(`tokens: wrote ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
